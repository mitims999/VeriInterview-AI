import type { FullReport } from "../api";
import Icon from "./Icon";

export interface SavedInterview {
  id: string;
  role: string;
  summary: string;
  report: FullReport;
}

export default function SavedInterviews({ interviews, onOpen }: { interviews: SavedInterview[]; onOpen: (id: string) => void }) {
  return <section className="saved-interviews" aria-label="Completed sample interviews">
    <div className="saved-intro"><span className="sample-label"><Icon name="file" size={15}/> SAMPLE LIBRARY</span><p>Three fictional interviews, already reviewed. Open a report to explore the answers, skill verification, and supporting evidence. These examples are available even when the analysis service is offline.</p></div>
    <div className="saved-grid">{interviews.map(interview => {
      const { assessment, qa_list, skill_verdicts } = interview.report;
      const minutes = Math.max(1, Math.round(qa_list.reduce((sum, qa) => sum + qa.answer_duration_sec + qa.response_latency_sec, 0) / 60));
      const initials = assessment.candidate_name.split(" ").map(part => part[0]).slice(0, 2).join("");
      return <article className="saved-card" key={interview.id}>
        <div className="saved-card-top"><span className="candidate-avatar">{initials}</span><span className="completed-label"><Icon name="check" size={12}/>Completed example</span></div>
        <h2>{assessment.candidate_name}</h2><p className="candidate-role">{interview.role}</p>
        <p className="candidate-summary">{interview.summary}</p>
        <div className="saved-stats"><span><strong>{qa_list.length}</strong> questions</span><span><strong>{skill_verdicts.length}</strong> skills</span><span><strong>{minutes} min</strong> recorded answers</span></div>
        <div className="saved-result"><div><span className="eyebrow">INTEGRITY RISK</span><span className={`badge ${assessment.risk_level.toLowerCase()}`}>{assessment.risk_level === "LOW" ? "Low" : assessment.risk_level === "MEDIUM" ? "Medium" : "High"} · {Math.round(assessment.risk_score)}/100</span></div><div><span className="eyebrow">CAPABILITY</span><strong>{Math.round(assessment.capability_score)}<small>/ 100</small></strong></div></div>
        <button className="button secondary" onClick={() => onOpen(interview.id)} aria-label={`View report for ${assessment.candidate_name}`}>View interview report<Icon name="arrow" size={16}/></button>
      </article>;
    })}</div>
    <div className="saved-footnote"><Icon name="shield" size={17}/><p>Names, resumes, answers, and media observations are synthetic. Scores were generated by the project’s scoring pipeline using its TF-IDF answer-matching fallback.</p></div>
  </section>;
}
